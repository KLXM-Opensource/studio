  <p class="lead">Kurzanleitungen für das, was im Alltag am häufigsten vorkommt.</p>
  <h3>Öffnungszeiten ändern</h3>
  <ol class="doc-steps">
    <li><?= e($settingsTitle) ?> → Stammdaten → Öffnungszeiten: je Wochentag einen Eintrag mit Von/Bis (Pause optional).</li>
    <li>Speichern – der Kontakt-Block und die Offline-Seite zeigen die neuen Zeiten sofort.</li>
  </ol>
  <h3>Hinweis auf Betriebsferien</h3>
  <ol class="doc-steps">
    <li><?= e($settingsTitle) ?> → Hinweisbalken: Text eingeben, „Hinweis anzeigen“ einschalten, speichern.</li>
    <li>Nach den Ferien den Schalter wieder ausschalten.</li>
  </ol>
  <h3>Farbe und Logo anpassen</h3>
  <ol class="doc-steps">
    <li>Verwaltung → Design: Vorlage wählen oder die Akzentfarbe unter „Farben“ ändern, speichern.</li>
    <li><?= e($settingsTitle) ?> → Darstellung → Logo (transparentes PNG, ca. 40 px hoch dargestellt). Ohne Logo erscheint der Kurzname mit einem Buchstaben-Signet in der Akzentfarbe.</li>
  </ol>
  <h3>Karte anzeigen</h3>
  <ol class="doc-steps">
    <li><?= e($settingsTitle) ?> → Stammdaten → Standort: „Aus Adresse ermitteln“ oder in die Karte klicken.</li>
    <li>Der Kontakt-Block zeigt die Karte automatisch; alternativ den Block <b>Karte</b> einfügen.</li>
  </ol>

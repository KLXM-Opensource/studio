  <h3>Tipps für dieses Design</h3>
  <ul>
    <li>Beginnen Sie jede Seite mit einem <b>Einstieg (Hero)</b> – er liefert die Hauptüberschrift. Kurze, kräftige Sätze (höchstens acht Wörter) wirken am besten; ein Wort in *Sternchen* wird hervorgehoben.</li>
    <li>Setzen Sie Farbflächen gezielt: ein Abschnitt „Blockfarbe“ oder „Dunkel“ pro Seite reicht meist. Gleiche Hintergründe hintereinander rücken automatisch zusammen.</li>
    <li>Das <b>Bento-Raster</b> lebt vom Wechsel: eine große Bild-Kachel, eine Zahl in Blockfarbe, dazu zwei, drei kleine Kacheln.</li>
    <li>Impressum und Datenschutz gehören nicht ins Menü – sie werden über <?= e($settingsTitle) ?> → Recht automatisch im Fußbereich verlinkt.</li>
  </ul>

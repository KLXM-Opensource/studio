  <h3>Tipps für dieses Design</h3>
  <ul>
    <li>Jede Seite braucht eine Hauptüberschrift: auf der Startseite die <b>Aktuelle Ausstellung</b> (Schalter „Titel ist die Hauptüberschrift“), auf Unterseiten einen <b>Einstieg</b> „Seitenkopf“. Detailseiten erledigen das selbst.</li>

  <p class="lead">„Essenz“ ist inspiriert von den zehn Thesen für gutes Design, die Dieter Rams formuliert hat: nützlich, verständlich, unaufdringlich, ehrlich, langlebig, konsequent bis ins Detail, umweltfreundlich – und so wenig Design wie möglich. Für Sie heißt das: <b>Inhalte stehen im Vordergrund, die Form hält sich zurück.</b></p>
  <h3>Die Bausteine der Formensprache</h3>
  <ul>
    <li><b>Eine Signalfarbe:</b> Sie erscheint nur dort, wo etwas zu tun ist oder etwas wichtig ist – Tasten (Buttons), Punkte, Skalen. Alles andere ist Graphit, Papier und Linie.</li>
    <li><b>8-Punkt-Raster:</b> Alle Abstände sind Vielfache einer Einheit. Deshalb wirken Seiten ruhig, auch wenn sie viele Bausteine enthalten.</li>
    <li><b>Paneele:</b> Karten sehen aus wie die Oberfläche eines Geräts – weicher Radius, feine Kante, leichter Schatten.</li>
    <li><b>Beschriftungen:</b> Dachzeilen, Nummern und Kennzahlen stehen in einer technischen Schrift mit gleich breiten Ziffern – wie die Skala an einem Gerät.</li>
    <li><b>Details mit Aufgabe:</b> Punktraster, Regler und Skalen kommen sparsam vor. Unter Design → „Bedienelement-Details“ lassen sie sich ganz abschalten.</li>
  </ul>
  <h3>Tipps für gute Seiten</h3>
  <ul>
    <li>Pro Abschnitt eine Aussage. Lieber zwei kurze Blöcke als einen langen.</li>
    <li>Dachzeilen kurz halten (ein bis drei Wörter) – sie wirken wie Randmarken.</li>
    <li>Kennzahlen und Füllstände nur mit belegbaren Werten verwenden.</li>
    <li>Für „Produkt“-Karten eignen sich freigestellte Bilder (PNG mit transparentem Hintergrund) am besten.</li>
    <li>Keine Bilder zur Hand? Alle Blöcke funktionieren ohne Bilder; der Einstieg „Mit Geräte-Paneel“ zeigt dann ein ruhiges Punktraster.</li>
  </ul>
